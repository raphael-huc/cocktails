/**
 * The canonical ingredients, and the names each one goes by in the sources.
 *
 * This table is the heart of the import: every source name is resolved to one
 * of these slugs, so that "Sugar syrup", "Gomme syrup" and "Simple syrup" end
 * up as a single ingredient in the user's bar. When a source uses a name that
 * is not listed, the import reports it; add it here as a new entry or as an
 * alias of an existing one.
 *
 * It is also where ingredients are named, in every language, and organised:
 * `pnpm import-recipes sync-ingredients` brings Directus in line with it.
 *
 * `parent` is an ingredient this one can stand in for. Usually it is the more
 * generic one (bourbon for whiskey), sometimes what it is made into (a lemon
 * for lemon juice, sugar for simple syrup): owning the child covers a recipe
 * that asks for the parent, never the other way round.
 */

export type IngredientCategory =
  | "spirit"
  | "liqueur"
  | "fortified_wine"
  | "bitters"
  | "juice"
  | "syrup"
  | "mixer"
  | "fresh"
  | "other";

export type CatalogIngredient = {
  slug: string;
  /** English name shown to users. */
  name: string;
  /** French name shown to users. */
  nameFr: string;
  category: IngredientCategory;
  parent?: string;
  /** Other spellings found in sources. The English name is always matched. */
  aliases?: string[];
  /** Everyone has it: lines using it never block a cocktail. */
  alwaysAvailable?: boolean;
  /**
   * Slugs of former ingredients merged into this one. When one still exists in
   * Directus, the sync moves its recipes and bar entries here and deletes it.
   */
  replaces?: string[];
};

